def haversine_mi(a: tuple, b: tuple) -> float:
    lat1, lon1, lat2, lon2 = map(math.radians, (*a, *b))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 3958.8 * 2 * math.asin(math.sqrt(h))


def state_code(name: str | None) -> str | None:
    if not name:
        return None
    n = name.strip()
    if len(n) == 2 and n.upper() in STATE_CENTROIDS:
        return n.upper()
    return STATE_NAMES.get(n.lower())


def estimate_road_miles(state: str | None, metro: bool = False) -> int | None:
    """Szacunkowa odległość drogowa od Des Plaines. Dla Chicago i okolic stałe 15 mil."""
    if metro:
        return 15
    c = STATE_CENTROIDS.get((state or "").upper())
    if not c:
        return None
    return int(round(haversine_mi(HOME, c) * ROAD_FACTOR / 10.0) * 10)
